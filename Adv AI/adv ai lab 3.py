# ----------------------------------------------------------------------
# ЗАДАНИЕ №7. Мини-исследование
# Гипотеза: студенты, которые занимаются более 6 часов в неделю,
# в среднем получают более высокий балл, чем остальные.
# ----------------------------------------------------------------------
df[df['Study_Hours'] > 6]['Average_Score'].mean()
df[df['Study_Hours'] <= 6]['Average_Score'].mean()
# график - тот же, что в задании №6 (Study_Hours -> Average_Score)

# ----------------------------------------------------------------------
# ЗАДАНИЕ №8. Сравнение категорий (groupby)
# ----------------------------------------------------------------------
df.groupby('Score_Category')[
    ['Average_Score', 'Attendance', 'Study_Hours']
].mean()

# ----------------------------------------------------------------------
# МИНИ-КЕЙС. Можно ли заранее определить студента с риском?
# ----------------------------------------------------------------------
# Шаг 1. Посещаемость менее 75 %
df[df['Attendance'] < 75]

# Шаг 2. Средний балл менее 70
df[df['Average_Score'] < 70]

# Шаг 3. Оба условия одновременно
df[
    (df['Attendance'] < 75) &
    (df['Average_Score'] < 70)
]

# Шаг 4. Часы обучения этих студентов
df[
    (df['Attendance'] < 75) &
    (df['Average_Score'] < 70)
][['Student', 'Attendance', 'Study_Hours', 'Average_Score']]

# ----------------------------------------------------------------------
# ДОПОЛНИТЕЛЬНОЕ ЗАДАНИЕ. Столбец Risk
# ----------------------------------------------------------------------
df['Risk'] = np.where(
    (df['Attendance'] < 75) |
    (df['Average_Score'] < 65),
    'Высокий риск',
    'Низкий риск'
)

df[['Student', 'Attendance', 'Average_Score', 'Risk']]

# ----------------------------------------------------------------------
# 14. Визуализация группы риска
# ----------------------------------------------------------------------
df['Risk'].value_counts()

df['Risk'].value_counts().plot(kind='bar')

